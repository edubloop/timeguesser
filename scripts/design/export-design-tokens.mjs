function buildPrototypeTokens(tokens) {
  const { colorsLight } = tokens;
  return {
    canonicalSources: ['constants/Colors.ts', 'constants/theme.ts'],
    tokens: {
      light: {
        bg: colorsLight.background,
        bgSecondary: colorsLight.backgroundSecondary,
        bgTertiary: colorsLight.backgroundTertiary,
        text: colorsLight.text,
        textSec: colorsLight.secondaryText,
        textTer: colorsLight.tertiaryText,
        accent: colorsLight.tint,
        accentPress: colorsLight.tintPressed,
        accentSubtle: colorsLight.tintSubtle,
        accentMuted: colorsLight.tintMuted,
        scoreEx: colorsLight.scoreExcellent,
        scoreGood: colorsLight.scoreGood,
        scoreFair: colorsLight.scoreFair,
        scorePoor: colorsLight.scorePoor,
        scoreFairSubtle: colorsLight.scoreFairSubtle,
        scorePoorSubtle: colorsLight.scorePoorSubtle,
        card: colorsLight.card,
        border: colorsLight.border,
      },
    },
    conventions: {
      settingsOrder,
    },
  };
}

function writeFileOrCheck(targetPath, content, checkMode) {
  const exists = fs.existsSync(targetPath);
  const current = exists ? fs.readFileSync(targetPath, 'utf8') : '';
  if (checkMode) {
    if (current !== content) {
      const minLength = Math.min(current.length, content.length);
      let diffIndex = 0;
      while (diffIndex < minLength && current[diffIndex] === content[diffIndex]) diffIndex += 1;
      throw new Error(
        `Drift detected: ${path.relative(rootDir, targetPath)} is out of date (diff index ${diffIndex}, current length ${current.length}, expected length ${content.length}).`
      );
    }
    return;
  }
  ensureDir(targetPath);
  fs.writeFileSync(targetPath, content, 'utf8');
}

function main() {
  const checkMode = process.argv.includes('--check');
  const colorsSource = fs.readFileSync(colorsPath, 'utf8');
  const themeSource = fs.readFileSync(themePath, 'utf8');

  const colors = evaluateObjectLiteral(extractObjectLiteral(colorsSource, 'Colors'));
  const spacing = evaluateObjectLiteral(extractObjectLiteral(themeSource, 'Spacing'));
  const radius = evaluateObjectLiteral(extractObjectLiteral(themeSource, 'Radius'));
  const layout = evaluateObjectLiteral(extractObjectLiteral(themeSource, 'Layout'));
  const typeScale = evaluateObjectLiteral(extractObjectLiteral(themeSource, 'TypeScale'));

  const tokens = {
    colorsLight: colors.light,
    colorsDark: colors.dark,
    spacing,
    radius,
    layout,
    typeScale,
    animation: {
      instant: 80,
      fast: 120,
      standard: 150,
      entrance: 200,
      exit: 120,
    },
    easing: {
      easeOut: 'cubic-bezier(0.0, 0.0, 0.2, 1)',
      easeIn: 'cubic-bezier(0.4, 0.0, 1, 1)',
      easeInOut: 'cubic-bezier(0.4, 0.0, 0.2, 1)',
    },
  };

  const cssOutput = `${buildCss(tokens)}\n`;
  const prototypePayload = buildPrototypeTokens(tokens);
  const tokensJsonOutput = `${JSON.stringify(prototypePayload, null, 2)}\n`;
  const tokensJsOutput = `// GENERATED FILE — DO NOT EDIT MANUALLY\nwindow.__TG_TOKENS__ = ${JSON.stringify(
    prototypePayload.tokens.light,
    null,
    2
  )};\nwindow.__TG_CONVENTIONS__ = ${JSON.stringify(prototypePayload.conventions, null, 2)};\n`;

  writeFileOrCheck(cssPath, cssOutput, checkMode);
  writeFileOrCheck(tokensJsonPath, tokensJsonOutput, checkMode);
  writeFileOrCheck(tokensJsPath, tokensJsOutput, checkMode);

  if (!checkMode) {
    console.log('Design tokens exported to:');
    console.log(`- ${path.relative(rootDir, cssPath)}`);
    console.log(`- ${path.relative(rootDir, tokensJsonPath)}`);
    console.log(`- ${path.relative(rootDir, tokensJsPath)}`);
  } else {
    console.log('Design token artifacts are up to date.');
  }
}

main();
