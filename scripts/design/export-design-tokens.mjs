function extractObjectLiteral(source, variableName) {
  const marker = `const ${variableName} =`;
  const start = source.indexOf(marker);
  if (start === -1) throw new Error(`Could not find "${variableName}" in source.`);
  const afterStart = source.slice(start + marker.length);
  const braceStart = afterStart.indexOf('{');
  if (braceStart === -1) throw new Error(`Could not find object start for ${variableName}.`);
  let depth = 0;
  let endIndex = -1;
  for (let i = braceStart; i < afterStart.length; i += 1) {
    const ch = afterStart[i];
    if (ch === '{') depth += 1;
    if (ch === '}') {
      depth -= 1;
      if (depth === 0) {
        endIndex = i;
        break;
      }
    }
  }
  if (endIndex === -1) throw new Error(`Could not find object end for ${variableName}.`);
  const objectLiteral = afterStart.slice(braceStart, endIndex + 1).trim();
  return objectLiteral.replace(/\sas const/g, '');
}

function evaluateObjectLiteral(objectLiteral) {
  return vm.runInNewContext(`(${objectLiteral})`, {}, { timeout: 1000 });
}

function ensureDir(filepath) {
  fs.mkdirSync(path.dirname(filepath), { recursive: true });
}

function formatCssVar(name, value, pad = 24) {
  return `  ${name.padEnd(pad)} ${value};`;
}

function toPx(value) {
  return typeof value === 'number' ? `${value}px` : String(value);
}

